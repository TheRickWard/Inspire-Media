def name():
    return f"{random.choice(first)} {random.choice(last)}"

def program(sections, start_item):
    rows, item = [], start_item
    used = set()
    for code, sname, session, genre, age, count, kind in sections:
        for _ in range(count):
            if kind == "duo":
                performer = f"{name()} & {name()}"
            elif kind == "troupe":
                performer = f"{random.choice(studios).split()[0]} {random.choice(['Juniors','Minis','Crew','Company'])}"
            else:
                performer = name()
                while performer in used:
                    performer = name()
                used.add(performer)
            rows.append(dict(item=str(item), section=code, section_name=sname, session=session, performer=performer,
                             studio=random.choice(studios), title=random.choice(titles), genre=genre, age=age))
            item += 1
    return rows

